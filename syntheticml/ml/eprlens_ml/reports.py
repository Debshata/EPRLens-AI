def f(x, d=3):
    return "—" if x is None else (f"{x:,.{d}f}" if isinstance(x, (int, float)) else str(x))


def publish_evaluation(run_dir, eval_dir, root, cfg):
    run_dir, eval_dir, root = Path(run_dir), Path(eval_dir), Path(root)
    for task in ("forecast", "anomaly"):
        d = eval_dir / task
        d.mkdir(parents=True, exist_ok=True)
        for p in (run_dir / "plots" / task).glob("*.png"):
            shutil.copy2(p, d / p.name)
        shutil.copy2(run_dir / task / "model_comparison.csv", d / "model_comparison.csv")
    ff = read_json(run_dir / "forecast" / "final.json")
    write_json({**ff, "baselines_train_validation": read_json(run_dir / "forecast" / "baselines.json"),
                "synthetic_only": True}, eval_dir / "forecast" / "metrics.json")
    af = read_json(run_dir / "anomaly" / "final.json")
    write_json({**af, "synthetic_only": True}, eval_dir / "anomaly" / "metrics.json")
    shutil.copy2(run_dir / "experiment_log.csv", eval_dir / "experiment_log.csv")
    write_json(read_json(run_dir / "status.json"), eval_dir / "run_status.json")
    report = model_report(run_dir, eval_dir, root, cfg)
    (root / "docs" / "ml-model-report.md").write_text(report, encoding="utf-8", newline="\n")
    (root / "ml" / "AWS_HANDOFF.md").write_text(aws_handoff(root, cfg, eval_dir), encoding="utf-8", newline="\n")



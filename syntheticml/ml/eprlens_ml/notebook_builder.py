def build_and_execute(run_dir, cfg, log, timeout=1800):
    nb = nbformat.v4.new_notebook()
    nb.cells = cells()
    nb.metadata["kernelspec"] = {"name": "python3", "display_name": "Python 3", "language": "python"}
    NB.parent.mkdir(parents=True, exist_ok=True)
    client = NotebookClient(nb, timeout=timeout, kernel_name="python3",
                            resources={"metadata": {"path": str(NB.parent)}})
    log.info("executing notebook (nbclient) …")
    client.execute()
    nbformat.write(nb, NB)
    errors = [o for c in nb.cells if c.cell_type == "code" for o in c.get("outputs", []) if o.get("output_type") == "error"]
    if errors:
        raise RuntimeError(f"notebook has {len(errors)} error output(s)")
    return NB

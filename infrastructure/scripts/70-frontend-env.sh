#!/usr/bin/env bash
# Writes frontend/.env.local (git-ignored) for LIVE mode, using a NEW access key of the narrow frontend IAM user.
# The secret is written straight into the file and never printed. Re-running replaces the key.
source "$(dirname "$0")/config.sh"
ENV_FILE="$REPO_ROOT/frontend/.env.local"
if [ -f "$ENV_FILE" ] && [ "${1:-}" != "--force" ]; then echo "$ENV_FILE exists; pass --force to replace it (rotates the key)"; exit 1; fi

# this user exists only for the local frontend: drop any old keys, then create a fresh one
for k in $(aws iam list-access-keys --user-name "$FRONTEND_USER" --query 'AccessKeyMetadata[].AccessKeyId' --output text); do
  aws iam delete-access-key --user-name "$FRONTEND_USER" --access-key-id "$k"
done
KEY_JSON="$(aws iam create-access-key --user-name "$FRONTEND_USER" --output json)"
umask 077
{
  echo "# Generated by infrastructure/scripts/70-frontend-env.sh — local only, never commit."
  echo "NEXT_PUBLIC_API_MODE=live"
  echo "AWS_REGION=$AWS_REGION"
  echo "AWS_ACCESS_KEY_ID=$(printf '%s' "$KEY_JSON" | python3 -c 'import json,sys;print(json.load(sys.stdin)["AccessKey"]["AccessKeyId"])')"
  echo "AWS_SECRET_ACCESS_KEY=$(printf '%s' "$KEY_JSON" | python3 -c 'import json,sys;print(json.load(sys.stdin)["AccessKey"]["SecretAccessKey"])')"
  echo "UPLOADS_BUCKET=$UPLOADS_BUCKET"
  echo "LAMBDA_PARSE_INVOICE=$(fn_name parse-invoice)"
  echo "LAMBDA_RECONCILE=$(fn_name reconcile)"
  echo "LAMBDA_CLASSIFY_IMAGE=$(fn_name classify-image)"
  echo "LAMBDA_FORECAST=$(fn_name forecast)"
  echo "LAMBDA_DETECT_ANOMALY=$(fn_name detect-anomaly)"
  echo "LAMBDA_SCENARIO_ENGINE=$(fn_name scenario-engine)"
  echo "LAMBDA_COMPANY_DATA=$(fn_name company-data)"
} > "$ENV_FILE"
unset KEY_JSON
echo "wrote $ENV_FILE (keys not shown). Start the frontend with: cd frontend && npm run build && npm run start"
